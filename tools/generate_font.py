"""Build the small 2bpp font subset used by the LCD renderer (requires Pillow).

Run only when UI strings change. Supply --font for another compatible CJK font.
The generated include is checked in, so firmware builds do not require Pillow.
"""
import argparse
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', type=Path, default=root / 'build/NotoSansCJKsc-Regular.otf')
args = parser.parse_args()
if not args.font.is_file():
    parser.error('Run python tools/fetch_font.py first, or pass --font with a licensed CJK font.')
source = (root / 'main/gamepad_render.c').read_text(encoding='utf-8')
chars = sorted(set(range(32, 127)) | {ord(c) for c in source if ord(c) > 127})
bitmap = bytearray()
tables = []
sizes = (12, 14, 18, 22)
for size in sizes:
    font = ImageFont.truetype(str(args.font), size)
    table = []
    top = font.getbbox('国Ag')[1]
    for code in chars:
        width = math.ceil(font.getlength(chr(code))) + 1
        im = Image.new('L', (width, size + 3))
        ImageDraw.Draw(im).text((0, -top), chr(code), font=font, fill=255)
        values = [(value * 3 + 127) // 255 for value in im.tobytes()]
        values += [0] * (-len(values) % 4)
        table.append((len(bitmap), width))
        bitmap.extend(sum(values[i+j] << (6-2*j) for j in range(4)) for i in range(0, len(values), 4))
    tables.append(table)
lines = ['/* Generated by tools/generate_font.py; 2bpp CJK subset.',
         ' * Default source: Noto Sans CJK SC; SIL OFL 1.1.',
         ' * See THIRD_PARTY_NOTICES.md and licenses/OFL-NotoSansCJK.txt. */',
         'typedef struct { uint32_t offset; uint8_t width; } font_glyph_t;',
         f'#define FONT_GLYPH_COUNT {len(chars)}',
         'static const uint8_t font_heights[] = {' + ','.join(str(s+3) for s in sizes) + '};',
         'static const uint32_t font_codepoints[] = {' + ','.join(hex(c) for c in chars) + '};',
         'static const uint8_t font_bitmap[] = {']
lines += [','.join(f'0x{v:02x}' for v in bitmap[i:i+24]) + ',' for i in range(0,len(bitmap),24)]
lines += ['};', 'static const font_glyph_t font_glyphs[4][FONT_GLYPH_COUNT] = {']
for table in tables:
    lines += ['{' + ','.join('{' + str(offset) + ',' + str(width) + '}' for offset,width in table) + '},']
lines += ['};', '']
(root / 'main/ui_font.inc').write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(chars)} glyphs x {len(sizes)} sizes; {len(bitmap)} bitmap bytes')
